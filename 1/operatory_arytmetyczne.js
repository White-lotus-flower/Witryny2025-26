const X = 9;
console.log(X + ' + 2 =', X + 2); //dodawanie
console.log(X + ' - 1 =', X - 1); //odejmowanie
console.log(X + ' * 3 =', X * 3); //mnozenie
console.log(X + ' / 2 =', X / 2); //dzielenie
console.log(X + ' mod 2 =', X % 2); 
console.log(X + ' mod 9 =', X % 9); //reszta z dzielenia
console.log(X + ' ^ 2 =', X ** 2);
console.log(X + ' ^ 3 =', X ** 3); //potegowanie

